/*
  Gourmet Meal Plan SPA - Alpine + Vanilla JavaScript Application
  ============================================================================
  Philosophy:
  - No build tools.
  - No server.
  - No external application framework beyond Alpine.js.
  - All data lives in assets/js/data.js as a static object.
  - All state that should survive refreshes (shopping-list checks) lives in localStorage.

  The code below deliberately uses plain, heavily-commented functions so a
  non-technical or lightly technical owner can modify labels, colors, or data
  behavior without learning a build pipeline.
*/

/**
 * Function preamble: normalizeText(value)
 * --------------------------------------------------------------------------
 * Objective:
 * Convert any human-facing string into a stable comparison key. This is used
 * for fuzzy recipe matching, searching, slug-like comparisons, and preserving
 * good behavior across accents, en-dashes, non-breaking spaces, and punctuation.
 *
 * Why it matters:
 * The meal plan contains rich culinary names with diacritics (Huancaína),
 * typographic punctuation (×, –), and shortened menu references ("Smoked Salmon
 * & Avocado Bagel") that should still resolve to the full recipe title.
 *
 * Assumptions:
 * The function is not meant for secure identifiers. It is a usability helper.
 */
function normalizeText(value) {
  return String(value || '')
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .replace(/[’‘]/g, "'")
    .replace(/[×]/g, ' x ')
    .replace(/[&]/g, ' and ')
    .replace(/[^a-zA-Z0-9]+/g, ' ')
    .toLowerCase()
    .trim();
}

/**
 * Function preamble: slugify(value)
 * --------------------------------------------------------------------------
 * Objective:
 * Produce a compact, URL-safe slug for recipes, sections, and localStorage keys.
 * This mirrors normalizeText but joins tokens with dashes.
 */
function slugify(value) {
  return normalizeText(value).replace(/\s+/g, '-');
}

/**
 * Function preamble: escapeHtml(value)
 * --------------------------------------------------------------------------
 * Objective:
 * Safely render plain text into HTML snippets generated by the app. This keeps
 * recipe text, data strings, and shopping items from accidentally becoming HTML.
 */
function escapeHtml(value) {
  return String(value || '')
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#039;');
}

/**
 * Function preamble: renderInlineMarkdown(value)
 * --------------------------------------------------------------------------
 * Objective:
 * Render the limited markdown syntax used in the generated meal plan. This is
 * intentionally small: it supports bold spans and preserves line breaks without
 * pulling in a full Markdown dependency.
 *
 * Design decision:
 * A no-dependency SPA should not add a markdown library. The parsed JSON already
 * contains structured arrays for most UI views. This helper only beautifies raw
 * recipe audit text when displayed.
 */
function renderInlineMarkdown(value) {
  return escapeHtml(value)
    .replace(/\*\*(.*?)\*\*/g, '<strong class="text-amber-200">$1</strong>')
    .replace(/\n/g, '<br>');
}

/**
 * Function preamble: mealPlanApp()
 * --------------------------------------------------------------------------
 * Objective:
 * Return the full Alpine.js component state and behavior for the SPA. Alpine
 * calls this function once from the root element in index.html. All routing,
 * filtering, modals, shopping checks, copy actions, and print states live here.
 *
 * Architecture:
 * - view: current top-level section (dashboard/calendar/week/day/recipes/shopping/knowledge)
 * - selectedDay / selectedWeek: contextual navigation state
 * - selectedRecipe: modal state
 * - query: recipe search text
 * - checkedItems: localStorage-backed map of shopping checkboxes
 */
function mealPlanApp() {
  return {
    data: window.MEAL_PLAN_DATA,
    view: 'dashboard',
    selectedWeek: 1,
    selectedDayIndex: 0,
    selectedRecipe: null,
    query: '',
    shoppingWeek: 1,
    toast: '',
    checkedItems: {},
    dayLabels: ['Mon', 'Tue', 'Wed', 'Thu', 'Fri', 'Sat', 'Sun'],
    mealSlots: [
      { key: 'breakfast', label: 'Breakfast', icon: '☕' },
      { key: 'lunch', label: 'Lunch', icon: '🥗' },
      { key: 'dinner', label: 'Dinner', icon: '🍽️' },
      { key: 'snackDessert', label: 'Optional Snack/Dessert', icon: '🍫' }
    ],

    /**
     * Function preamble: init()
     * ----------------------------------------------------------------------
     * Objective:
     * Initialize persistent state, normalize recipe indexes, and activate the
     * hash router. The app is intentionally URL-addressable so shared links like
     * #recipes or #day/2/4 open the intended view immediately.
     */
    init() {
      this.loadChecks();
      this.ensureRecipeIndex();
      this.readRoute();
      window.addEventListener('hashchange', () => this.readRoute());
    },

    /**
     * Function preamble: ensureRecipeIndex()
     * ----------------------------------------------------------------------
     * Objective:
     * Add runtime-only helpers to recipe objects: normalizedName and slug.
     * These fields make fuzzy menu-to-recipe matching fast and predictable.
     */
    ensureRecipeIndex() {
      this.data.recipes.forEach((recipe) => {
        recipe.normalizedName = normalizeText(recipe.name);
        recipe.slug = recipe.id || slugify(recipe.name);
        // es-PE-first: pull the authored es title from the weighed-7 (nutrition-reviewed.json)
        if (window.GOURMET_NUTRITION_DATA) {
          const curated = window.GOURMET_NUTRITION_DATA.curatedRecipes.find((c) => c.id === recipe.slug || c.title === recipe.name);
          if (curated && curated.es) recipe.es = curated.es;
        }
      });
    },

    /**
     * Function preamble: navigate(target)
     * ----------------------------------------------------------------------
     * Objective:
     * Centralize route changes so buttons, keyboard shortcuts, and deep links all
     * use the same path format. This is client-side routing without page reloads.
     */
    navigate(target) {
      window.location.hash = target;
    },

    /**
     * Function preamble: readRoute()
     * ----------------------------------------------------------------------
     * Objective:
     * Interpret location.hash and update Alpine state. Supported routes:
     * #dashboard, #calendar, #week/1, #day/1/0, #recipes, #shopping/2,
     * #knowledge.
     */
    readRoute() {
      const raw = (window.location.hash || '#dashboard').replace(/^#/, '');
      const parts = raw.split('/').filter(Boolean);
      const page = parts[0] || 'dashboard';
      if (['dashboard', 'calendar', 'recipes', 'knowledge', 'compliance', 'nutrition'].includes(page)) {
        this.view = page;
      } else if (page === 'week') {
        this.view = 'week';
        this.selectedWeek = Math.min(4, Math.max(1, Number(parts[1] || 1)));
      } else if (page === 'day') {
        this.view = 'day';
        this.selectedWeek = Math.min(4, Math.max(1, Number(parts[1] || 1)));
        this.selectedDayIndex = Math.min(6, Math.max(0, Number(parts[2] || 0)));
      } else if (page === 'shopping') {
        this.view = 'shopping';
        this.shoppingWeek = Math.min(4, Math.max(1, Number(parts[1] || 1)));
      } else {
        this.view = 'dashboard';
      }
      window.scrollTo({ top: 0, behavior: 'smooth' });
    },

    /**
     * Function preamble: complianceMetrics()
     * ----------------------------------------------------------------------
     * Objective:
     * Summarize the DGA compliance audit into compact dashboard metrics.
     * The method intentionally reads from the static data object rather than
     * recalculating everything at runtime, because the recipe-level audit was
     * performed offline during the project revision pass.
     *
     * Validation logic:
     * The returned values are defensive. If a future editor removes the audit
     * block, the UI still renders safe zero values instead of crashing.
     */
    complianceMetrics() {
      const counts = this.data.complianceAudit?.counts || {};
      return [
        { label: 'Recipes', value: counts.recipesReviewed || this.data.recipes.length, note: 'Every recipe has a guideline audit block.' },
        { label: 'Menus', value: counts.dailyMenusReviewed || this.data.dailyPlans.length, note: 'All daily meal slots were checked for recipe links.' },
        { label: 'Lists', value: counts.shoppingListsReviewed || this.data.shoppingLists.length, note: 'Shopping lists remove processed-meat and additive traps.' },
        { label: 'Rule set', value: (this.data.dietGuidelineRules || []).length, note: 'PDF-derived checks embedded in the data layer.' }
      ];
    },

    /**
     * Function preamble: currentWeekOverview()
     * ----------------------------------------------------------------------
     * Objective:
     * Return the selected week's descriptive theme and highlights. If data is
     * missing, return a safe empty object instead of throwing.
     */
    currentWeekOverview() {
      return this.data.weeklyOverviews.find((week) => week.week === this.selectedWeek) || { highlights: [] };
    },

    /**
     * Function preamble: weekDays(weekNumber)
     * ----------------------------------------------------------------------
     * Objective:
     * Return the seven menu entries for a week. The source data is flat for easy
     * search and export; this helper groups it for visual display.
     */
    weekDays(weekNumber) {
      return this.data.dailyPlans.filter((day) => day.week === Number(weekNumber));
    },

    /**
     * Function preamble: selectedDay()
     * ----------------------------------------------------------------------
     * Objective:
     * Return the selected day menu based on selectedWeek and selectedDayIndex.
     */
    selectedDay() {
      return this.weekDays(this.selectedWeek)[this.selectedDayIndex] || this.data.dailyPlans[0];
    },

    /**
     * Function preamble: mealToRecipe(mealName)
     * ----------------------------------------------------------------------
     * Objective:
     * Convert a meal name from the calendar into the most plausible full recipe.
     * It uses exact matching first, then bidirectional containment, then token
     * overlap. This handles shortened menu labels such as "Lucuma Tiramisu" and
     * longer recipe titles such as "Lucuma Tiramisu (Italian × Peruvian)".
     */
    mealToRecipe(mealName) {
      const needle = normalizeText(mealName);
      if (!needle) return null;
      let match = this.data.recipes.find((recipe) => recipe.normalizedName === needle);
      if (match) return match;
      match = this.data.recipes.find((recipe) => recipe.normalizedName.includes(needle) || needle.includes(recipe.normalizedName));
      if (match) return match;
      const tokens = needle.split(' ').filter((token) => token.length > 2);
      let best = null;
      let bestScore = 0;
      this.data.recipes.forEach((recipe) => {
        const score = tokens.reduce((sum, token) => sum + (recipe.normalizedName.includes(token) ? 1 : 0), 0);
        if (score > bestScore) {
          bestScore = score;
          best = recipe;
        }
      });
      return bestScore >= Math.min(3, tokens.length) ? best : null;
    },

    /**
     * Function preamble: openRecipeByMeal(mealName)
     * ----------------------------------------------------------------------
     * Objective:
     * Open the recipe modal from a calendar/day/week meal label. If no recipe can
     * be matched, display a helpful toast instead of failing silently.
     */
    openRecipeByMeal(mealName) {
      const recipe = this.mealToRecipe(mealName);
      if (recipe) {
        this.selectedRecipe = recipe;
      } else {
        this.showToast(`No full recipe was found for “${mealName}”.`);
      }
    },

    /**
     * Function preamble: filteredRecipes()
     * ----------------------------------------------------------------------
     * Objective:
     * Return recipes filtered by the user's search query across recipe name,
     * cuisine, ingredients, method, and science note. This makes the recipe
     * library useful for searches like "aji", "chocolate", or "sous-vide".
     */
    get filteredRecipes() {
      const q = normalizeText(this.query);
      if (!q) return this.data.recipes;
      return this.data.recipes.filter((recipe) => normalizeText([
        recipe.name,
        recipe.cuisine,
        recipe.ingredients.join(' '),
        recipe.method.join(' '),
        recipe.whyThisWorks,
        recipe.plating
      ].join(' ')).includes(q));
    },

    /**
     * Function preamble: shoppingListForWeek(weekNumber)
     * ----------------------------------------------------------------------
     * Objective:
     * Retrieve the categorized shopping list for a week. Returns a stable empty
     * list if the data is not present.
     */
    shoppingListForWeek(weekNumber) {
      const list = this.data.shoppingLists.find((week) => week.week === Number(weekNumber));
      return list ? list.categories : [];
    },

    /**
     * Function preamble: checkKey(week, category, item)
     * ----------------------------------------------------------------------
     * Objective:
     * Create a deterministic key for each shopping checkbox. It includes week,
     * category, and item text to avoid collisions between repeated ingredients.
     */
    checkKey(week, category, item) {
      return `week-${week}::${slugify(category)}::${slugify(item)}`;
    },

    /**
     * Function preamble: loadChecks()
     * ----------------------------------------------------------------------
     * Objective:
     * Load shopping checkbox state from localStorage. JSON parsing is wrapped in
     * a try/catch so a corrupted value never breaks the application.
     */
    loadChecks() {
      try {
        this.checkedItems = JSON.parse(localStorage.getItem('gourmet-shopping-checks') || '{}');
      } catch (_error) {
        this.checkedItems = {};
      }
    },

    /**
     * Function preamble: saveChecks()
     * ----------------------------------------------------------------------
     * Objective:
     * Persist shopping checkbox state in localStorage so checked items remain
     * checked after refreshes or browser restarts.
     */
    saveChecks() {
      localStorage.setItem('gourmet-shopping-checks', JSON.stringify(this.checkedItems));
    },

    /**
     * Function preamble: toggleCheck(key)
     * ----------------------------------------------------------------------
     * Objective:
     * Toggle a shopping item and immediately persist the result. Alpine's
     * reactivity updates the checkbox and strikethrough state in place.
     */
    toggleCheck(key) {
      this.checkedItems[key] = !this.checkedItems[key];
      this.saveChecks();
    },

    /**
     * Function preamble: copyShoppingList()
     * ----------------------------------------------------------------------
     * Objective:
     * Copy the currently selected week's shopping list as clean, categorized
     * plain text. The method uses the modern Clipboard API with a fallback toast
     * if the browser blocks clipboard access.
     */
    async copyShoppingList() {
      const lines = [`Week ${this.shoppingWeek} Shopping List`];
      this.shoppingListForWeek(this.shoppingWeek).forEach((category) => {
        lines.push('', category.category);
        category.items.forEach((item) => lines.push(`- ${item}`));
      });
      try {
        await navigator.clipboard.writeText(lines.join('\n'));
        this.showToast('Shopping list copied to clipboard.');
      } catch (_error) {
        this.showToast('Clipboard access was blocked; select and copy manually.');
      }
    },

    /**
     * Function preamble: resetShoppingWeek()
     * ----------------------------------------------------------------------
     * Objective:
     * Clear checkbox progress only for the currently selected week. This avoids
     * deleting progress for other weeks.
     */
    resetShoppingWeek() {
      const prefix = `week-${this.shoppingWeek}::`;
      Object.keys(this.checkedItems).forEach((key) => {
        if (key.startsWith(prefix)) delete this.checkedItems[key];
      });
      this.saveChecks();
      this.showToast(`Week ${this.shoppingWeek} checks cleared.`);
    },

    /**
     * Function preamble: shoppingProgress(weekNumber)
     * ----------------------------------------------------------------------
     * Objective:
     * Calculate checked/total shopping items for a week. This powers the small
     * progress pill in the shopping UI.
     */
    shoppingProgress(weekNumber) {
      const categories = this.shoppingListForWeek(weekNumber);
      let total = 0;
      let checked = 0;
      categories.forEach((category) => {
        category.items.forEach((item) => {
          total += 1;
          if (this.checkedItems[this.checkKey(weekNumber, category.category, item)]) checked += 1;
        });
      });
      return { checked, total, pct: total ? Math.round((checked / total) * 100) : 0 };
    },

    /**
     * Function preamble: printCurrentView()
     * ----------------------------------------------------------------------
     * Objective:
     * Trigger the browser print dialog. CSS media rules in assets/css/tailwind.css
     * simplify the page and hide navigation for a clean recipe/list printout.
     */
    printCurrentView() {
      window.print();
    },

    /**
     * Function preamble: exportData()
     * ----------------------------------------------------------------------
     * Objective:
     * Download the embedded JSON data for audit, backup, or future migration to
     * a richer app. This helps validate that no recipe content is trapped in UI.
     */
    exportData() {
      const blob = new Blob([JSON.stringify(this.data, null, 2)], { type: 'application/json' });
      const url = URL.createObjectURL(blob);
      const a = document.createElement('a');
      a.href = url;
      a.download = 'gourmet-meal-plan-data.json';
      a.click();
      URL.revokeObjectURL(url);
      this.showToast('Structured meal-plan JSON downloaded.');
    },

    /**
     * Function preamble: showToast(message)
     * ----------------------------------------------------------------------
     * Objective:
     * Display short, non-blocking feedback. The timeout clears the message so the
     * UI does not remain cluttered.
     */
    showToast(message) {
      this.toast = message;
      setTimeout(() => { this.toast = ''; }, 2400);
    },

    /**
     * Function preamble: recipeSectionCount(recipe)
     * ----------------------------------------------------------------------
     * Objective:
     * Small UI helper for showing how complete a recipe is. Because data.js also
     * preserves fullMarkdown, a recipe with few parsed bullets still has complete
     * source text available in the modal.
     */
    recipeSectionCount(recipe) {
      return ['miseEnPlace', 'ingredients', 'method'].reduce((sum, key) => sum + (recipe[key]?.length || 0), 0);
    },

    renderInlineMarkdown
  };
}
/* Alpine binds this component from index.html via x-data="mealPlanApp()";
 * the explicit global keeps the binding alive if app.js ever converts to a module. */
window.mealPlanApp = mealPlanApp;
