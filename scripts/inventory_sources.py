#!/usr/bin/env python3
"""P0.2 — source inventory audit (metadata ONLY, stdlib).

For every file under data/private/, context/ and the unreviewed user drop
"Context information/": record path, size, SHA-256, media type, confidentiality
classification and whether it is gitignored (!== tracked). NO file contents are
read beyond binary hash streaming. Output: docs/source-inventory.json plus a
markdown table snippet for docs/SOURCE_INVENTORY.md.

Re-running is idempotent; hashes must not change between runs (evidence of
post-commit drift/tampering is flagged in tests/source_inventory.test.cjs).
"""
from pathlib import Path
import hashlib
import json
import mimetypes
import subprocess
import sys

root = Path(__file__).resolve().parents[1]
mimetypes.init()

CONFIDENTIALITY = {
    'data/private': 'PRIVATE (owner originals: orders XLSX, PDF, generated report)',
    'context/private': 'PRIVATE until individually reviewed',
    'context': 'PRIVATE — unreviewed order-derived analysis; audit before any use',
    'Context information': 'PRIVATE — user drop, unreviewed, duplicate of context/ variant (verify hash equality)',
}


def sha256_of(path: Path) -> str:
    h = hashlib.sha256()
    with path.open('rb') as f:
        for chunk in iter(lambda: f.read(1 << 20), b''):
            h.update(chunk)
    return h.hexdigest()


def tracked_files() -> set[str]:
    out = subprocess.run(['git', 'ls-files'], cwd=root, capture_output=True, text=True).stdout
    return set(out.splitlines())


def main() -> int:
    entries = []
    for dir_name in ('data/private', 'context/private', 'context', 'Context information'):
        base = root / dir_name
        if not base.is_dir():
            continue
        for p in sorted(base.rglob('*')):
            if not p.is_file() or p.name == 'README.md':
                continue
            rel = p.relative_to(root).as_posix()
            top = dir_name if '/' not in rel else rel.split('/')[0]
            entries.append({
                'path': rel,
                'sizeBytes': p.stat().st_size,
                'sha256': sha256_of(p),
                'mediaType': mimetypes.guess_type(p.name)[0] or 'application/octet-stream',
                'confidentiality': CONFIDENTIALITY.get(top, 'UNCLASSIFIED'),
                'gitTracked': rel in tracked_files(),
            })

    duplicates = []
    for i, a in enumerate(entries):
        for b in entries[i + 1:]:
            if a['sha256'] == b['sha256'] and a['path'] != b['path']:
                duplicates.append([a['path'], b['path']])

    doc = {
        'schema': 'source-inventory/v1',
        'generatedInDirectory': root.name,
        'privateEntryCount': len(entries),
        'entries': entries,
        'duplicateHashPairs': duplicates,
        'note': 'Metadata only. Entries include user content we never open in-session without need.',
    }
    out_json = root / 'docs' / 'source-inventory.json'
    out_json.write_text(json.dumps(doc, indent=1, ensure_ascii=False) + '\n', encoding='utf8')

    lines = [
        '', '## P0.2 hash audit (metadata only, generated by scripts/inventory_sources.py)', '',
        '| Path (PRIVATE, untracked) | Bytes | SHA-256 (first 12) | Media type |',
        '|---|---|---|---|',
    ]
    for e in entries:
        state = 'TRACKED?!' if e['gitTracked'] else 'untracked'
        lines.append(f"| `{e['path']}` ({state}) | {e['sizeBytes']:,} | `{e['sha256'][:12]}` | {e['mediaType']} |")
    if duplicates:
        lines.append(f"- duplicate pairs by identical hash: {duplicates}")
    out_md = root / 'docs' / 'SOURCE_INVENTORY_APPEND.md'
    out_md.write_text('\n'.join(lines) + '\n', encoding='utf8')

    tracked_private = [e for e in entries if e['gitTracked']]
    print(f"entries={len(entries)} duplicates={duplicates} tracked_private={tracked_private}")
    if tracked_private:
        print('FATAL: private files are git-tracked', file=sys.stderr)
        return 1
    return 0


if __name__ == '__main__':
    sys.exit(main())
